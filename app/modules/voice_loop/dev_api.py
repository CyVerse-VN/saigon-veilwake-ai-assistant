"""Bounded, single-process demo jobs. Never used by the verified /v1 pipeline."""

from __future__ import annotations

import hashlib
import threading
import time
from collections.abc import Callable
from concurrent.futures import ThreadPoolExecutor
from dataclasses import dataclass
from datetime import datetime, timedelta, timezone
from pathlib import Path
from uuid import uuid4

from starlette.exceptions import HTTPException

from app.core.config import Settings
from app.modules.voice_loop.service import VoiceLoopService
from app.schemas.conversation import ResponseMode
from app.schemas.dev_voice import (
    DevAccepted,
    DevAnswer,
    DevAudio,
    DevConversation,
    DevError,
    DevInput,
    DevTtsProvider,
    DevTtsSelection,
    DevTurn,
)

TERMINAL = {"COMPLETED", "COMPLETED_TEXT_ONLY", "FAILED"}


class DevApiError(HTTPException):
    def __init__(self, status: int, code: str, message: str, *, retryable: bool = False):
        self.status = status
        self.error = DevError(code=code, message=message, retryable=retryable)
        super().__init__(status_code=status, detail=message)


class _Expired(Exception):
    pass


@dataclass
class _Session:
    owner: str
    expires: float


@dataclass
class _Job:
    owner: str
    result: DevTurn
    deadline: float
    retain_until: float
    directory: Path
    fingerprint: str
    idempotency_key: str
    audio_expires: float | None = None
    running: bool = True


class DevVoiceManager:
    def __init__(
        self,
        settings: Settings,
        root: Path,
        factory: Callable[[DevTtsProvider, str | None], VoiceLoopService],
        *,
        clock: Callable[[], float] = time.monotonic,
    ) -> None:
        self.settings = settings
        self.root = root
        if root.is_symlink():
            raise ValueError("Dev audio directory must not be a symlink.")
        root.mkdir(parents=True, exist_ok=True)
        self.factory = factory
        self.clock = clock
        self.lock = threading.RLock()
        self.sessions: dict[str, _Session] = {}
        self.jobs: dict[str, _Job] = {}
        self.keys: dict[tuple[str, str], str] = {}
        self.executor = ThreadPoolExecutor(
            max_workers=settings.dev_voice_max_concurrent_turns, thread_name_prefix="dev-voice"
        )
        self.closed = False

    @staticmethod
    def _date(seconds: float) -> datetime:
        return datetime.now(timezone.utc) + timedelta(seconds=seconds)

    def create_conversation(self, owner: str) -> DevConversation:
        with self.lock:
            self.sweep()
            if len(self.sessions) >= self.settings.dev_voice_max_sessions:
                raise DevApiError(429, "SESSION_LIMIT", "Too many test sessions; try later.")
            conversation_id = "devconv_" + uuid4().hex
            ttl = self.settings.dev_voice_session_ttl_seconds
            self.sessions[conversation_id] = _Session(owner, self.clock() + ttl)
            return DevConversation(
                conversation_id=conversation_id,
                expires_at=self._date(ttl),
                turn_timeout_seconds=self.settings.dev_voice_turn_timeout_seconds,
            )

    def accept(
        self,
        owner: str,
        conversation_id: str,
        key: str,
        *,
        message: str | None = None,
        audio: bytes | None = None,
        response_mode: ResponseMode = ResponseMode.TEXT_AND_VOICE,
        tts_provider: DevTtsProvider | None = None,
        vieneu_voice: str | None = None,
        story_access_level: int = 0,
    ) -> DevAccepted:
        provider = tts_provider or self.settings.tts_provider
        if provider == "gemini" and vieneu_voice is not None:
            raise DevApiError(422, "INVALID_TTS_OPTION", "A VieNeu voice requires VieNeu TTS.")
        if provider == "vieneu":
            voice = (vieneu_voice or self.settings.vieneu_tts_voice).strip()
            if not voice:
                raise DevApiError(422, "INVALID_TTS_OPTION", "Select a VieNeu voice.")
        elif provider == "elevenlabs":
            fallback_el_voice = self.settings.elevenlabs_tts_voice_id
            if not fallback_el_voice and not vieneu_voice:
                fallback_el_voice = Settings().elevenlabs_tts_voice_id
            voice = (vieneu_voice or fallback_el_voice or "").strip() or None
        else:
            voice = None
        # Fingerprint content, mode, and selected test provider; a retry cannot silently
        # reuse an audio result generated by a different TTS option.
        digest = hashlib.sha256(
            (b"voice:" if audio is not None else b"text:")
            + response_mode.value.encode()
            + b":"
            + provider.encode()
            + b":"
            + (voice or "").encode()
            + f":{story_access_level}:".encode()
            + (audio if audio is not None else (message or "").encode())
        ).hexdigest()
        with self.lock:
            self.sweep()
            session = self.sessions.get(conversation_id)
            if session is None or session.owner != owner:
                raise DevApiError(404, "CONVERSATION_NOT_FOUND", "Test conversation not found.")
            old_id = self.keys.get((conversation_id, key))
            if old_id is not None:
                old = self.jobs[old_id]
                if old.fingerprint != digest:
                    raise DevApiError(
                        409, "IDEMPOTENCY_CONFLICT", "Key was used for different content."
                    )
                return self._accepted(old.result)
            running = [job for job in self.jobs.values() if job.running]
            if any(job.result.conversation_id == conversation_id for job in running):
                raise DevApiError(409, "TURN_BUSY", "This conversation already has an active turn.")
            if self.closed or len(running) >= self.settings.dev_voice_max_concurrent_turns:
                raise DevApiError(
                    429, "BUSY", "Voice workers are busy; retry later.", retryable=True
                )
            if len(self.jobs) >= self.settings.dev_voice_max_turns:
                raise DevApiError(429, "TURN_LIMIT", "Test turn storage is full; retry later.")
            turn_id = "devturn_" + uuid4().hex
            result = DevTurn(
                turn_id=turn_id,
                conversation_id=conversation_id,
                input=DevInput(type="voice" if audio is not None else "text", transcript=message),
                story_access_level=story_access_level,
                tts=DevTtsSelection(provider=provider, voice=voice),
                audio=DevAudio(
                    status="PENDING"
                    if response_mode == ResponseMode.TEXT_AND_VOICE
                    else "NOT_REQUESTED"
                ),
                created_at=datetime.now(timezone.utc),
            )
            now = self.clock()
            job = _Job(
                owner,
                result,
                now + self.settings.dev_voice_turn_timeout_seconds,
                now + self.settings.dev_voice_session_ttl_seconds,
                self.root / turn_id,
                digest,
                key,
            )
            self.jobs[turn_id] = job
            self.keys[(conversation_id, key)] = turn_id
            try:
                self.executor.submit(
                    self._run, job, audio, message, response_mode, story_access_level
                )
            except RuntimeError:
                self.jobs.pop(turn_id)
                self.keys.pop((conversation_id, key))
                raise DevApiError(503, "SHUTTING_DOWN", "Voice worker is shutting down.") from None
            return self._accepted(result)

    @staticmethod
    def _accepted(result: DevTurn) -> DevAccepted:
        return DevAccepted(
            turn_id=result.turn_id,
            conversation_id=result.conversation_id,
            status=result.status,
            status_url=f"/dev/v1/turns/{result.turn_id}",
        )

    def _owned(self, owner: str, turn_id: str) -> _Job:
        job = self.jobs.get(turn_id)
        if job is None or job.owner != owner:
            raise DevApiError(404, "TURN_NOT_FOUND", "Test turn not found.")
        return job

    def get_turn(self, owner: str, turn_id: str) -> DevTurn:
        with self.lock:
            self.sweep()
            return self._owned(owner, turn_id).result.model_copy(deep=True)

    def read_audio(self, owner: str, turn_id: str) -> bytes:
        with self.lock:
            self.sweep()
            job = self._owned(owner, turn_id)
            if job.result.audio.status == "EXPIRED":
                raise DevApiError(
                    410, "AUDIO_EXPIRED", "Audio has expired; text is still available."
                )
            if job.result.audio.status != "READY":
                raise DevApiError(
                    409, "AUDIO_NOT_READY", "No playable audio is available for this turn."
                )
            try:
                # Read a bounded snapshot, so TTL cleanup cannot race a later file response.
                return (job.directory / "response.wav").read_bytes()
            except OSError:
                raise DevApiError(410, "AUDIO_EXPIRED", "Audio is no longer available.") from None

    def _timeout(self, job: _Job) -> None:
        result = job.result
        if result.status not in TERMINAL:
            result.status = "COMPLETED_TEXT_ONLY" if result.answer else "FAILED"
            result.audio = DevAudio(status="UNAVAILABLE")
            result.error = DevError(
                code="TURN_TIMEOUT", message="Voice turn timed out.", retryable=True
            )

    def _live(self, job: _Job) -> None:
        if self.closed or self.clock() >= job.deadline or job.result.status in TERMINAL:
            self._timeout(job)
            raise _Expired

    def _progress(self, job: _Job, event: str, text: str | None, seconds: float | None) -> None:
        with self.lock:
            self._live(job)
            if event == "TRANSCRIBED":
                job.result.input.transcript = text
                job.result.timings.stt_seconds = seconds
            elif event == "GENERATED":
                job.result.answer = DevAnswer(text=text or "")
                job.result.timings.llm_seconds = seconds
            else:
                job.result.status = event

    def _run(
        self,
        job: _Job,
        audio: bytes | None,
        message: str | None,
        response_mode: ResponseMode,
        story_access_level: int = 0,
    ) -> None:
        try:
            with self.lock:
                self._live(job)
            job.directory.mkdir(exist_ok=False)
            # Per-turn adapters keep mutable provider diagnostics isolated.
            service = self.factory(job.result.tts.provider, job.result.tts.voice)

            def progress(event: str, text: str | None, seconds: float | None) -> None:
                self._progress(job, event, text, seconds)

            wants_audio = response_mode == ResponseMode.TEXT_AND_VOICE
            output = job.directory / "response.wav"
            conv_id = job.result.conversation_id
            if audio is not None:
                input_path = job.directory / "microphone.wav"
                input_path.write_bytes(audio)
                completed = service.process(
                    input_path,
                    output,
                    progress=progress,
                    wants_audio=wants_audio,
                    story_access_level=story_access_level,
                    conversation_id=conv_id,
                )
            else:
                completed = service.process_text(
                    message or "",
                    output,
                    progress=progress,
                    wants_audio=wants_audio,
                    story_access_level=story_access_level,
                    conversation_id=conv_id,
                )
            with self.lock:
                self._live(job)
                job.result.input.transcript = completed.transcript
                job.result.answer = DevAnswer(
                    text=completed.answer,
                    verification_status=completed.verification_status,
                )
                job.result.citations = list(completed.citations)
                job.result.timings.stt_seconds = (
                    completed.stt_seconds if audio is not None else None
                )
                job.result.timings.llm_seconds = completed.llm_seconds
                job.result.timings.tts_seconds = completed.tts_seconds
                valid_audio = (
                    completed.audio_path == output
                    and output.is_file()
                    and 0 < output.stat().st_size <= 8 * 1024 * 1024
                )
                if completed.audio_path is not None and valid_audio:
                    ttl = self.settings.dev_voice_audio_ttl_seconds
                    job.audio_expires = self.clock() + ttl
                    job.retain_until = max(job.retain_until, job.audio_expires + 60)
                    job.result.audio = DevAudio(
                        status="READY",
                        endpoint=f"/dev/v1/turns/{job.result.turn_id}/audio",
                        expires_at=self._date(ttl),
                    )
                    job.result.status = "COMPLETED"
                elif completed.tts_error or wants_audio:
                    job.result.audio = DevAudio(status="UNAVAILABLE")
                    job.result.status = "COMPLETED_TEXT_ONLY"
                    job.result.error = DevError(
                        code="TTS_UNAVAILABLE",
                        message="Voice is unavailable; the text response is ready.",
                    )
                else:
                    job.result.status = "COMPLETED"
        except _Expired:
            pass
        except Exception:
            with self.lock:
                if job.result.status not in TERMINAL:
                    stage = job.result.status
                    job.result.status = "COMPLETED_TEXT_ONLY" if job.result.answer else "FAILED"
                    job.result.audio = DevAudio(status="UNAVAILABLE")
                    # Never publish str(exc), provider objects, headers, or request bodies.
                    job.result.error = DevError(
                        code=f"{stage}_FAILED",
                        message="Voice processing failed. Please try again.",
                        retryable=True,
                    )
        finally:
            with self.lock:
                self._remove_file(job.directory / "microphone.wav")
                if self.closed or job.result.audio.status != "READY":
                    self._remove_file(job.directory / "response.wav")
                self._remove_empty(job.directory)
                # Do not release a slot on watchdog timeout until the real thread exits.
                job.running = False

    @staticmethod
    def _remove_file(path: Path) -> None:
        try:
            path.unlink(missing_ok=True)
        except OSError:
            pass

    @staticmethod
    def _remove_empty(path: Path) -> None:
        try:
            path.rmdir()
        except OSError:
            pass

    def sweep(self) -> None:
        """Called periodically and on reads, even if the client stops polling."""
        with self.lock:
            now = self.clock()
            for turn_id, job in list(self.jobs.items()):
                if now >= job.deadline:
                    self._timeout(job)
                if job.audio_expires is not None and now >= job.audio_expires:
                    job.result.audio.status = "EXPIRED"
                    job.result.audio.endpoint = None
                    self._remove_file(job.directory / "response.wav")
                    self._remove_empty(job.directory)
                if not job.running and now >= job.retain_until:
                    self._remove_file(job.directory / "response.wav")
                    self._remove_empty(job.directory)
                    self.keys.pop((job.result.conversation_id, job.idempotency_key), None)
                    del self.jobs[turn_id]
            self.sessions = {key: item for key, item in self.sessions.items() if now < item.expires}
            # After a restart, only clean known filenames in old, owned UUID directories.
            active = {job.directory.name for job in self.jobs.values()}
            try:
                directories = list(self.root.iterdir())
            except OSError:
                return
            for directory in directories:
                suffix = directory.name.removeprefix("devturn_")
                if (
                    directory.name in active
                    or directory.is_symlink()
                    or not directory.is_dir()
                    or not directory.name.startswith("devturn_")
                    or len(suffix) != 32
                    or any(char not in "0123456789abcdef" for char in suffix)
                ):
                    continue
                try:
                    age = time.time() - directory.stat().st_mtime
                    if (
                        age
                        >= self.settings.dev_voice_audio_ttl_seconds
                        + self.settings.dev_voice_turn_timeout_seconds
                    ):
                        for name in ("microphone.wav", "response.wav"):
                            self._remove_file(directory / name)
                        self._remove_empty(directory)
                except OSError:
                    pass

    def close(self) -> None:
        with self.lock:
            self.closed = True
            for job in self.jobs.values():
                self._timeout(job)
                if not job.running:
                    self._remove_file(job.directory / "response.wav")
                    self._remove_empty(job.directory)
        self.executor.shutdown(wait=False, cancel_futures=True)
